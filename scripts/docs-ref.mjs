#!/usr/bin/env node
// Writes the generated reference pages from the code, so they can't drift:
//   docs/reference/cli.md        every command's `--help`, from the built CLI
//   docs/reference/mcp-tools.md  the `workmesh mcp` server's tools/list answer
// and checks that docs/reference/config.md (written by hand) names every config key in `configSchema` and every
// WORKMESH_* environment variable the CLI reads.
//
//   npm run build -w @b3os/workmesh && npm run docs:ref    # regenerate after changing a command or tool
//   npm run docs:ref:check                                 # what CI runs: fails when a page is stale
//
// The CLI runs in a throwaway HOME (it copies pre-rename config at start and must never touch yours), without colour.
import { spawn, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "packages/cli/dist/index.js");
const outDir = path.join(root, "docs/reference");
const check = process.argv.includes("--check");
const REGEN = "npm run build -w @b3os/workmesh && npm run docs:ref";

function die(message) {
  console.error(`docs:ref: ${message}`);
  process.exit(1);
}

if (!fs.existsSync(entry)) die(`no built CLI at ${path.relative(root, entry)}; run: npm run build -w @b3os/workmesh`);

const home = fs.mkdtempSync(path.join(os.tmpdir(), "wm-docs-ref-"));
const env = {
  HOME: home,
  PATH: process.env.PATH ?? "/usr/bin:/bin",
  XDG_CONFIG_HOME: path.join(home, ".config"),
  XDG_STATE_HOME: path.join(home, ".local/state"),
  CLAUDE_CONFIG_DIR: path.join(home, ".claude"),
  CODEX_HOME: path.join(home, ".codex"),
  WORKMESH_NO_SERVICE: "1",
  NO_COLOR: "1",
};

// ---------------------------------------------------------------------------------------------------------- CLI help

function help(args) {
  const r = spawnSync(process.execPath, [entry, ...args, "--help"], { env, encoding: "utf8", cwd: home });
  if (r.status !== 0) die(`workmesh ${args.join(" ")} --help exited ${r.status}: ${r.stderr}`);
  return r.stdout.replace(/\s+$/, "");
}

/** The "Commands:" block of a help text: [{ name, usage, description }], without commander's own `help`. */
function commandsOf(text) {
  const lines = text.split("\n");
  const start = lines.indexOf("Commands:");
  if (start < 0) return [];
  const out = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === "") break;
    const m = /^ {2}(\S.*?)(?: {2,}(.*))?$/.exec(line);
    if (m) {
      out.push({ name: m[1].split(" ")[0], usage: m[1].trim(), description: (m[2] ?? "").trim() });
    } else if (out.length) {
      const last = out[out.length - 1];
      last.description = `${last.description} ${line.trim()}`.trim();
    }
  }
  return out.filter((c) => c.name !== "help");
}

const anchor = (title) => title.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-");
const cell = (s) => s.replace(/\|/g, "\\|");

function cliPage() {
  const top = help([]);
  const rows = [];
  const sections = [];
  const walk = (args, list) => {
    for (const c of list) {
      const argv = [...args, c.name];
      const title = `workmesh ${argv.join(" ")}`;
      const text = help(argv);
      rows.push(`| [\`${title}\`](#${anchor(title)}) | ${cell(c.description)} |`);
      sections.push(`## ${title}\n\n\`\`\`text\n${text}\n\`\`\``);
      walk(argv, commandsOf(text));
    }
  };
  walk([], commandsOf(top));
  return [
    "# CLI reference",
    "",
    "Every `workmesh` command and its options, as `--help` prints them. This page is generated by",
    "`npm run docs:ref` (`scripts/docs-ref.mjs`) from the built CLI; CI fails when it is out of date. To change it, change",
    "the command in `packages/cli/src/index.ts` and run the script again. `agentblip` is an alias for `workmesh`.",
    "",
    "For what to run when, start with the [guide](../guide/getting-started.md).",
    "",
    "| Command | What it does |",
    "|---|---|",
    ...rows,
    "",
    "## workmesh",
    "",
    "```text",
    top,
    "```",
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------------------------------------- MCP tools

function mcpList() {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [entry, "mcp"], { env, cwd: home, stdio: ["pipe", "pipe", "pipe"] });
    const timer = setTimeout(() => {
      child.kill();
      reject(new Error("workmesh mcp didn't answer tools/list within 10 s"));
    }, 10_000);
    let buf = "";
    const answers = {};
    child.stdout.on("data", (d) => {
      buf += d;
      let i;
      while ((i = buf.indexOf("\n")) >= 0) {
        const line = buf.slice(0, i).trim();
        buf = buf.slice(i + 1);
        if (!line) continue;
        const msg = JSON.parse(line);
        answers[msg.id] = msg.result;
        if (answers[1] && answers[2]) {
          clearTimeout(timer);
          child.kill();
          resolve({ init: answers[1], tools: answers[2].tools });
        }
      }
    });
    child.on("error", reject);
    const send = (m) => child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", ...m })}\n`);
    send({ id: 1, method: "initialize", params: { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "docs-ref", version: "0" } } });
    send({ method: "notifications/initialized" });
    send({ id: 2, method: "tools/list" });
  });
}

function typeOf(p) {
  if (p.enum) return p.enum.map((v) => `\`${v}\``).join(" \\| ");
  if (p.type === "array") return `${p.items?.enum ? `(${p.items.enum.map((v) => `\`${v}\``).join(" \\| ")})` : p.items?.type ?? "any"}[]`;
  return p.type ?? "any";
}

function mcpPage({ init, tools }) {
  const kind = (t) => (t.annotations?.readOnlyHint ? "reads" : "writes to the hub");
  const rows = tools.map((t) => `| [\`${t.name}\`](#${anchor(t.name)}) | ${kind(t)} | ${cell(t.description)} |`);
  const sections = tools.map((t) => {
    const props = Object.entries(t.inputSchema.properties ?? {});
    const req = new Set(t.inputSchema.required ?? []);
    const params = props.length
      ? [
          "| Parameter | Type | Required | Description |",
          "|---|---|---|---|",
          ...props.map(([k, p]) => `| \`${k}\` | ${typeOf(p)} | ${req.has(k) ? "yes" : "no"} | ${cell(p.description ?? "")} |`),
        ].join("\n")
      : "No parameters.";
    const hints = t.annotations?.readOnlyHint
      ? "Read-only."
      : `Changes team state on the hub; destructive: ${t.annotations?.destructiveHint ? "yes" : "no"}.`;
    return `## ${t.name}\n\n${t.description}\n\n${hints}\n\n${params}`;
  });
  return [
    "# MCP tools reference",
    "",
    "The tools `workmesh mcp` gives Claude Code and Codex sessions (`workmesh init` registers the server as `workmesh`).",
    "Each call goes to your local daemon, which makes the hub call; the MCP server holds no token. This page is generated",
    "by `npm run docs:ref` (`scripts/docs-ref.mjs`) from the server's `tools/list` answer; CI fails when it is out of",
    "date. To change it, change `MCP_TOOLS` in `packages/cli/src/mcp/server.ts` and run the script again.",
    "",
    "Every tool carries MCP annotations (read-only, or non-destructive and closed-world), so Codex runs them without",
    "asking. Claude Code ignores the hints; its own permission settings apply. How to use them together:",
    "[Working together](../guide/working-together.md).",
    "",
    "What an agent reads when it connects (the server's `instructions`):",
    "",
    ...init.instructions.match(/.{1,110}(\s|$)/g).map((l) => `> ${l.trim()}`),
    "",
    "| Tool | Kind | What it does |",
    "|---|---|---|",
    ...rows,
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------------------------- config.md coverage

/** Every key path in configSchema (`adapters.codex.sessionsDir`), from the source, bundled on the fly. */
async function configKeys() {
  const { build } = await import("esbuild");
  const out = path.join(home, "config.mjs");
  await build({
    entryPoints: [path.join(root, "packages/cli/src/lib/config.ts")],
    bundle: true,
    platform: "node",
    format: "esm",
    outfile: out,
    logLevel: "silent",
  });
  const { configSchema } = await import(pathToFileURL(out).href);
  const keys = [];
  // hub.project is the hub's sharing rule, written at pairing: one key, not documented field by field.
  const opaque = new Set(["hub.project"]);
  const walk = (schema, prefix) => {
    let s = schema;
    while (["optional", "default", "catch", "nullable", "readonly", "prefault"].includes(s._zod.def.type)) s = s._zod.def.innerType;
    if (s._zod.def.type !== "object") return;
    for (const [k, v] of Object.entries(s._zod.def.shape)) {
      const p = prefix ? `${prefix}.${k}` : k;
      keys.push(p);
      if (!opaque.has(p)) walk(v, p);
    }
  };
  walk(configSchema, "");
  return keys;
}

/** WORKMESH_* variables the CLI reads (`envSetting("PORT")` reads WORKMESH_PORT, then AGENTBLIP_PORT). */
function envVars() {
  // Carried into the daemon service's and auto-update's environment, read by nothing in this version.
  const internal = new Set(["WORKMESH_CONFIG"]);
  const names = new Set();
  const files = [];
  const list = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const f = path.join(dir, e.name);
      if (e.isDirectory()) list(f);
      else if (f.endsWith(".ts")) files.push(f);
    }
  };
  list(path.join(root, "packages/cli/src"));
  for (const f of files) {
    const src = fs.readFileSync(f, "utf8");
    for (const m of src.matchAll(/envSetting\("([A-Z_]+)"\)/g)) names.add(`WORKMESH_${m[1]}`);
    for (const m of src.matchAll(/\bWORKMESH_[A-Z][A-Z0-9_]*\b/g)) if (!m[0].endsWith("_RE")) names.add(m[0]);
  }
  return [...names].filter((n) => !internal.has(n)).sort();
}

async function configCoverage() {
  const file = path.join(outDir, "config.md");
  const doc = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  const missing = [];
  for (const k of await configKeys()) if (!doc.includes(`\`${k}\``)) missing.push(`config key ${k}`);
  for (const v of envVars()) if (!doc.includes(`\`${v}\``)) missing.push(`environment variable ${v}`);
  return missing;
}

// -------------------------------------------------------------------------------------------------------------- main

const pages = {
  "cli.md": cliPage(),
  "mcp-tools.md": mcpPage(await mcpList()),
};
const missing = await configCoverage();
fs.rmSync(home, { recursive: true, force: true });

let stale = 0;
for (const [name, text] of Object.entries(pages)) {
  const file = path.join(outDir, name);
  const now = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : undefined;
  if (now === text) continue;
  if (check) {
    console.error(`docs:ref: docs/reference/${name} is out of date with the code`);
    stale += 1;
  } else {
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote docs/reference/${name}`);
  }
}
for (const m of missing) console.error(`docs:ref: docs/reference/config.md doesn't name the ${m}`);
if (stale) console.error(`docs:ref: run \`${REGEN}\` and commit the result`);
if (stale || missing.length) process.exit(1);
if (check) console.log("docs:ref: docs/reference is up to date");
